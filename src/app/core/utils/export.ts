/**
 * Client-side exports. CSV is written with a BOM so Excel opens UTF-8 (₹, names) correctly.
 * XLSX is a minimal, dependency-free Office Open XML workbook (one sheet, bold header row),
 * zipped with the STORE method.
 */

export type Cell = string | number | null | undefined;

export interface ExportTable {
  headers: string[];
  rows: Cell[][];
}

const download = (blob: Blob, filename: string): void => {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
};

// ---------- CSV ----------

const csvCell = (value: Cell): string => {
  if (value === null || value === undefined) return '';
  const text = String(value);
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
};

export const downloadCsv = (filename: string, table: ExportTable): void => {
  const lines = [table.headers, ...table.rows].map((row) => row.map(csvCell).join(','));
  download(new Blob(['﻿' + lines.join('\r\n')], { type: 'text/csv;charset=utf-8' }), `${filename}.csv`);
};

// ---------- XLSX ----------

const xmlEscape = (text: string): string =>
  text
    // Strip characters that are illegal in XML 1.0.
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const columnName = (index: number): string => {
  let name = '';
  for (let n = index + 1; n > 0; n = Math.floor((n - 1) / 26)) {
    name = String.fromCharCode(65 + ((n - 1) % 26)) + name;
  }
  return name;
};

const sheetXml = (table: ExportTable): string => {
  const widths = table.headers.map((h, i) =>
    Math.min(60, Math.max(h.length, ...table.rows.map((r) => String(r[i] ?? '').length)) + 2)
  );
  const cols = widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('');

  const rowXml = (row: Cell[], r: number, header: boolean): string => {
    const cells = row
      .map((value, c) => {
        const ref = `${columnName(c)}${r}`;
        const style = header ? ' s="1"' : '';
        if (typeof value === 'number' && Number.isFinite(value)) return `<c r="${ref}"${style}><v>${value}</v></c>`;
        if (value === null || value === undefined || value === '') return '';
        return `<c r="${ref}" t="inlineStr"${style}><is><t xml:space="preserve">${xmlEscape(String(value))}</t></is></c>`;
      })
      .join('');
    return `<row r="${r}">${cells}</row>`;
  };

  const rows = [rowXml(table.headers, 1, true), ...table.rows.map((row, i) => rowXml(row, i + 2, false))].join('');
  return (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>' +
    '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">' +
    '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>' +
    `<cols>${cols}</cols><sheetData>${rows}</sheetData></worksheet>`
  );
};

